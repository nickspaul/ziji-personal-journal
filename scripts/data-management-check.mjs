// Pure UI logic checks. No network requests or personal database access.
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from '../frontend/node_modules/typescript/lib/typescript.js';
const source=await readFile(new URL('../frontend/src/dataManagement.ts',import.meta.url),'utf8');
const transpile=source=>ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const ledger=transpile(await readFile(new URL('../frontend/src/ledgerReview.ts',import.meta.url),'utf8'));
const js=transpile(source).replace("'./ledgerReview'", "'data:text/javascript;base64,"+Buffer.from(ledger).toString('base64')+"'");
const {valueFor,matchesRecord,compareRecords,calculationNotes,csvCell,dataGroups,dataGuide}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const product={id:'product',version:1,brand:'测试品牌',name:'测试款',packagePrice:100};
const collections={products:[product]};
const fields=[{key:'productId',label:'香烟',type:'product'},{key:'source',label:'来源',type:'select',options:[{value:'SELF',label:'自购'}]},{key:'count',label:'根数',type:'number'},{key:'notes',label:'备注',type:'text'}];
const row={id:'test',version:1,productId:'product',count:2,source:'SELF',notes:'午饭后'};
assert.ok(matchesRecord(row,fields,collections,'测试品牌 自购 午饭'));
assert.equal(matchesRecord(row,fields,collections,'测试品牌 别人提供'),false);
assert.equal(valueFor({...row,snapshotName:'旧名称'},fields[0],collections),'旧名称');
assert.ok(matchesRecord({...row,snapshotName:'旧名称'},fields,collections,'旧名称'));
assert.equal(matchesRecord({...row,snapshotName:'旧名称'},fields,collections,'测试款'),false);
assert.equal(valueFor({...row,active:false},{key:'active',type:'boolean'},collections),'否');
assert.equal(valueFor({...row,cost:0},{key:'cost',type:'number'},collections),'¥0.00');
assert.equal(valueFor({...row,cost:null},{key:'cost',type:'number'},collections),'—');
const counts=[{...row,id:'10',count:10},{...row,id:'missing',count:null},{...row,id:'2',count:2}];
assert.deepEqual([...counts].sort((a,b)=>compareRecords(a,b,'count','asc',fields,collections)).map(r=>r.id),['2','10','missing']);
assert.deepEqual([...counts].sort((a,b)=>compareRecords(a,b,'count','desc',fields,collections)).map(r=>r.id),['10','2','missing']);
const dates=[{...row,id:'older',effectiveDate:'2026-01-01',createdAt:'2026-11-01'},{...row,id:'newer',effectiveDate:'2026-10-01',createdAt:'2026-10-01'}];
assert.equal(dates.sort((a,b)=>compareRecords(a,b,'recordDate','desc',fields,collections))[0].id,'newer');
assert.equal(compareRecords({...row,heightCm:180,weightKg:60},{...row,heightCm:180,weightKg:90},'bmi','asc',[{key:'bmi',type:'number'}],{})<0,true);
const smoke=calculationNotes('smoking',{...row,cost:2,snapshotUnitPrice:1,snapshotPriceType:'PERSONAL',snapshotUnitCount:20});
assert.equal(smoke[0].value,'2 根 × 1 元/根 = ¥2.00');
assert.match(calculationNotes('smoking',{...row,cost:0,costType:'GIFT'})[0].value,/别人提供/);
assert.equal(calculationNotes('smoking',{...row,cost:null})[0].label,'费用待补');
const drink=calculationNotes('drinks',{...row,inputMode:'BOTTLES',bottles:2,share:0.5,snapshotBottleMl:500,actualMl:500,equivalentBottles:1,snapshotUnitPrice:6,cost:6,snapshotAbv:4,ethanolGrams:15.78});
assert.ok(drink.some(n=>n.value==='2 瓶 × 500 ml/瓶 × 0.5 本人比例 = 500 ml'));
assert.ok(drink.some(n=>n.value==='15.78 g ÷ 0.789 ÷ 0.42 = 47.6 ml'));
assert.match(calculationNotes('body',{...row,weightKg:80,heightCm:null})[0].value,/同时有身高和体重/);
assert.equal(csvCell('=1+1'),'"\'=1+1"');
assert.equal(csvCell('备注"包含引号'),'"备注""包含引号"');
assert.deepEqual(dataGroups.flatMap(g=>g.collections).sort(),Object.keys(dataGuide).sort());
assert.ok(dataGuide.ledger);
console.log('22 checks passed: Chinese search, historical names, null/zero, numeric/date/BMI sorting, historical cost explanations, alcohol conversion and CSV escaping.');

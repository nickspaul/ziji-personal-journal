CREATE TABLE zj_tasks (
  id CHAR(36) NOT NULL PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 1,
  createdAt DATETIME(6) NOT NULL,
  updatedAt DATETIME(6) NOT NULL,
  deleted BOOLEAN NOT NULL DEFAULT FALSE,
  title VARCHAR(500) NOT NULL,
  content TEXT NULL,
  status VARCHAR(40) NOT NULL,
  plannedDate DATE NULL,
  dueDate DATE NULL,
  completedDate DATE NULL,
  result TEXT NULL,
  important BOOLEAN NOT NULL DEFAULT FALSE,
  tags JSON NULL,
  derivedJson JSON NULL,
  INDEX idx_tasks_status_date (deleted,status,plannedDate,id),
  INDEX idx_tasks_due (deleted,dueDate,id),
  INDEX idx_tasks_completed (deleted,completedDate,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE zj_journal (
  id CHAR(36) NOT NULL PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 1,
  createdAt DATETIME(6) NOT NULL,
  updatedAt DATETIME(6) NOT NULL,
  deleted BOOLEAN NOT NULL DEFAULT FALSE,
  title VARCHAR(500) NOT NULL,
  content TEXT NULL,
  category VARCHAR(40) NULL,
  startDate DATE NOT NULL,
  endDate DATE NULL,
  timeMode VARCHAR(40) NOT NULL,
  period VARCHAR(40) NULL,
  startTime TIME NULL,
  endTime TIME NULL,
  place VARCHAR(500) NULL,
  people JSON NULL,
  tags JSON NULL,
  taskId CHAR(36) NULL,
  derivedJson JSON NULL,
  INDEX idx_journal_start (deleted,startDate,startTime,id),
  INDEX idx_journal_end (deleted,endDate,id),
  INDEX idx_journal_category (deleted,category,startDate,id),
  INDEX idx_journal_task (taskId,deleted,startDate,id),
  CONSTRAINT fk_journal_task FOREIGN KEY (taskId) REFERENCES zj_tasks(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
